export function svgInterp(arr, t) {
  const u = Math.max(0, Math.min(1, t));
  const n = arr.length;
  if (u <= arr[0][0]) return arr[0][1];
  if (u >= arr[n - 1][0]) return arr[n - 1][1];
  let lo = 0;
  let hi = n - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (arr[mid][0] <= u) lo = mid;
    else hi = mid;
  }
  const [t0, v0] = arr[lo];
  const [t1, v1] = arr[hi];
  return v0 + ((v1 - v0) * (u - t0)) / (t1 - t0 || 1);
}

